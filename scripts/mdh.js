/* =========================================================
   البحث عن الكلمات
========================================================= */

function containsAny(text, words) {

  const lower = text.toLowerCase();

  return words.some(word =>
    lower.includes(word.toLowerCase())
  );
}


/* =========================================================
   هل جبد سحتوت؟
========================================================= */

function mentionsShtot(text) {

  const names = [
    "سحتوت",
    "سحتوتي",
    "shtot",
    "sh6ot"
  ];

  return containsAny(text, names);
}


/* =========================================================
   اكتشاف نوع الرسالة
========================================================= */

function detectType(text) {

  if (mentionsShtot(text)) {

    if (containsAny(text, WORDS.criticism)) {
      return "defense";
    }

    if (
      containsAny(text, WORDS.praise) ||
      containsAny(text, WORDS.positive)
    ) {
      return "praise";
    }

    return "shtot";
  }

  if (containsAny(text, WORDS.greeting)) {
    return "greeting";
  }

  if (containsAny(text, WORDS.laugh)) {
    return "laugh";
  }

  if (containsAny(text, WORDS.question)) {
    return "question";
  }

  if (containsAny(text, WORDS.thanks)) {
    return "thanks";
  }

  if (containsAny(text, WORDS.love)) {
    return "love";
  }

  return "general";
}


/* =========================================================
   تركيب الرد
========================================================= */

function generateReply(text) {

  const type = detectType(text);

  let reply;

  switch (type) {

    case "defense":

      reply =
        `${random(DEFENSE_LINES)} ${random(ENDINGS)}`;

      break;

    case "praise":

      reply =
        `${random(OPENERS)}، ${random(PRAISE_LINES)} ${random(ENDINGS)}`;

      break;

    case "shtot":

      reply =
        `${random(OPENERS)}، سحتوت حاضر والهيبة حاضرة معاه ${random(ENDINGS)}`;

      break;

    case "greeting":

      reply =
        random(GREETING_LINES);

      break;

    case "laugh":

      reply =
        random(LAUGH_LINES);

      break;

    case "question":

      reply =
        random(QUESTION_LINES);

      break;

    case "thanks":

      reply =
        `العفو، سحتوت ديما حاضر 🤝 ${random(ENDINGS)}`;

      break;

    case "love":

      reply =
        `دخلنا للرومانسية دابا 😂❤️ ${random(ENDINGS)}`;

      break;

    default:

      /*
       * نستعمل البنك الكبير في الرسائل العامة
       */
      reply = random(GENERATED);

      break;
  }

  /*
   * إذا كانت الرسالة كتذكر سحتوت،
   * نتأكد أن الرد فيه الاسم.
   */

  if (mentionsShtot(text) && !reply.includes("سحتوت")) {

    reply = `👑 سحتوت: ${reply}`;

  }

  return reply;
}


