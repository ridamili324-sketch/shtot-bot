  onStart: async function ({ event, message }) {
    global.kilaActive ??= {};

    const threadID = String(event.threadID);
    const userID = String(event.senderID);
    const text = String(event.body || "").trim();

    global.kilaActive[threadID] ??= {};

    const command = text
      .replace(/^كيلا\s*/i, "")
      .trim();

    if (
      command === "تفعيل" ||
      command === "تشغيل" ||
      command === "شغل"
    ) {
      global.kilaActive[threadID][userID] = true;

      return message.reply(
        "واخا ❤️😂 تفعّلات ليك كيلا، من دابا أي رسالة منك غادي نجاوبك عليها."
      );
    }

    if (
      command === "تعطيل" ||
      command === "توقيف" ||
      command === "وقف" ||
      command === "حبس"
    ) {
      delete global.kilaActive[threadID][userID];

      return message.reply(
        "صافي 😂❤️ وقفتها عليك."
      );
    }

    return message.reply(
      "🌸 أوامر كيلا:\n\n" +
      "كيلا تفعيل ❤️\n" +
      "كيلا تعطيل 😂"
    );
  },

