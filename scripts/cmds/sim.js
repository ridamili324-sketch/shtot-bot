	onStart: async function ({ event, message }) {

		global.lisaShtot ??= {};

		const threadID = event.threadID;

		const body = String(event.body || "");

		const option = body
			.replace(/^\S+\s*/, "")
			.trim()
			.toLowerCase();

		// -----------------------------
		// تشغيل
		// -----------------------------

		if (
			option === "تشغيل" ||
			option === "شغل"
		) {

			if (global.lisaShtot[threadID]) {
				return message.reply(
					"⚠️ ليسا راه خدامة دابا."
				);
			}

			global.lisaShtot[threadID] = true;

			return message.reply(
				"💗 تم تشغيل ليسا.\n\n" +
				"👀 غادي تراقب الرسائل.\n" +
				"👑 ملي تشوف اسم «سحتوت» غادي ترد برد مناسب.\n\n" +
				"🛑 للإيقاف: ليسا توقيف"
			);
		}

		// -----------------------------
		// توقيف
		// -----------------------------

		if (
			option === "توقيف" ||
			option === "وقف" ||
			option === "حبس"
		) {

			if (!global.lisaShtot[threadID]) {
				return message.reply(
					"⚠️ ليسا راه موقفـة أصلاً."
				);
			}

			delete global.lisaShtot[threadID];

			return message.reply(
				"🛑 تم توقيف ليسا."
			);
		}

		// -----------------------------
		// المساعدة
		// -----------------------------

		return message.reply(
			"💗 أوامر ليسا:\n\n" +
			"▶️ ليسا تشغيل\n" +
			"⏹️ ليسا توقيف\n\n" +
			"👑 منين تكون خدامة، ليسا غادي ترد ملي تشوف اسم سحتوت."
		);
	},


